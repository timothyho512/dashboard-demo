-- DBQ console: assumed generic schema (PostgreSQL 17 dialect; see dialects.md for Oracle / SQL Server).
-- This is an ASSUMPTION for design and validation. Map each column to the real DBQ tables before building.
-- Validated on a private PostgreSQL 17.8 cluster with ~1.6M synthetic rows (see seed.sql, panels.sql).

DROP TABLE IF EXISTS dbq_action_audit, dbq_snapshot, dbq_attempt, dbq_worker, dbq_queue_config, dbq_item CASCADE;

-- ---------------------------------------------------------------------------
-- The hot queue table (one row per work item). This is the only table the real DBQ is assumed to have.
-- ---------------------------------------------------------------------------
CREATE TABLE dbq_item (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 84000000) PRIMARY KEY,
  queue_name    VARCHAR(64)   NOT NULL,              -- topic, e.g. payments.inbound
  status        VARCHAR(16)   NOT NULL,              -- QUEUED | CLAIMED | PROCESSING | DONE | FAILED | DEAD | CANCELLED
                                                     --   FAILED    = last attempt failed, waiting for retry at available_at
                                                     --   CANCELLED = added by the console's cancel action (consumers never claim it)
  priority      SMALLINT      NOT NULL DEFAULT 0,
  payload_ref   VARCHAR(256),                        -- business key or pointer to the payload
  producer      VARCHAR(64),                         -- optional; e.g. AIS (else infer from queue_name)
  batch_ref     VARCHAR(128),                        -- optional; upstream file name / batch id
  created_at    TIMESTAMP     NOT NULL,
  available_at  TIMESTAMP     NOT NULL,              -- not claimable before this (retry backoff / delayed delivery)
  claimed_by    VARCHAR(128),                        -- worker id, e.g. mmp-app-03:4211 (host:pid)
  claimed_at    TIMESTAMP,
  heartbeat_at  TIMESTAMP,                           -- refreshed by the worker while it holds the claim
  attempts      INT           NOT NULL DEFAULT 0,
  max_attempts  INT           NOT NULL DEFAULT 10,
  last_error    VARCHAR(4000),
  completed_at  TIMESTAMP,                           -- set on DONE, DEAD and CANCELLED
  CONSTRAINT dbq_item_status_ck CHECK (status IN ('QUEUED','CLAIMED','PROCESSING','DONE','FAILED','DEAD','CANCELLED'))
);

-- Index design: small PARTIAL indexes over the few "open" rows, so console reads never scan DONE history.
-- Ready / backlog index. Needed by: claim query, P1 (waiting, scheduled), P2 (oldest wait, backoff), P13b, P14 (drain), P18 (snapshot).
-- id is the claim query's tie-breaker (ORDER BY available_at, id), so the claim reads exactly LIMIT index entries, no sort.
CREATE INDEX dbq_item_ready_ix   ON dbq_item (queue_name, available_at, id)
  WHERE status IN ('QUEUED','FAILED');
-- In-flight index. Needed by: P1 (in flight, stuck), P7 (consumers), P8 (stuck claims), P17 (release), heartbeat UPDATE.
CREATE INDEX dbq_item_claimed_ix ON dbq_item (queue_name, claimed_by, heartbeat_at)
  WHERE status IN ('CLAIMED','PROCESSING');
-- Dead-letter index. Needed by: P1 (dead), P9, P10 (fingerprints over dead items), P17 (retry dead).
CREATE INDEX dbq_item_dead_ix    ON dbq_item (queue_name, completed_at)
  WHERE status = 'DEAD';
-- Arrivals by time. Needed by: P1 / P5 / P14 (in per minute), P12 (per producer / batch, spike), P13 (today's batches).
CREATE INDEX dbq_item_created_ix ON dbq_item (queue_name, created_at);
-- Completions by time. Needed by: P1 / P5 / P14 (out per minute), P6 (wait percentiles), P7 (completed per worker), P15 (item SLO).
CREATE INDEX dbq_item_completed_ix ON dbq_item (queue_name, completed_at)
  WHERE completed_at IS NOT NULL;
-- Lookups. Needed by: P13 (one batch drill-down), P16 (item journey by business key or file).
CREATE INDEX dbq_item_batch_ix   ON dbq_item (batch_ref) WHERE batch_ref IS NOT NULL;
CREATE INDEX dbq_item_payload_ix ON dbq_item (payload_ref);

-- ---------------------------------------------------------------------------
-- Optional helper tables (recommended; none is required for a first version).
-- ---------------------------------------------------------------------------

-- Per-queue settings: SLO, stale threshold, pause switch, owner. Needed by: P1, P2, P4, P8, P14, P15, P17 (pause), claim query.
CREATE TABLE dbq_queue_config (
  queue_name     VARCHAR(64) PRIMARY KEY,
  slo_wait_s     INT         NOT NULL,               -- oldest waiting item must be younger than this
  stale_after_s  INT         NOT NULL DEFAULT 90,    -- claim is stuck when heartbeat is older (3 x heartbeat interval)
  paused         BOOLEAN     NOT NULL DEFAULT FALSE, -- consumers must check this in the claim query
  owner_team     VARCHAR(64)
);

-- Process heartbeat registry: consumer liveness even when a worker holds no claims. Needed by: P1 (consumers), P7, P17 (double guard), P19 (STOP).
CREATE TABLE dbq_worker (
  worker_id     VARCHAR(128) NOT NULL,               -- same value the worker writes into dbq_item.claimed_by
  queue_name    VARCHAR(64)  NOT NULL,
  host          VARCHAR(64)  NOT NULL,
  service       VARCHAR(32)  NOT NULL,
  started_at    TIMESTAMP    NOT NULL,
  heartbeat_at  TIMESTAMP    NOT NULL,
  version       VARCHAR(32),
  PRIMARY KEY (worker_id, queue_name)
);

-- Attempt log: one row per finished attempt. Needed by: P7 (failures per worker), P9, P10 (history), P11 (retry storm), P16 (journey), P18 (failed_1m).
CREATE TABLE dbq_attempt (
  item_id      BIGINT       NOT NULL,
  attempt      INT          NOT NULL,
  queue_name   VARCHAR(64)  NOT NULL,
  worker       VARCHAR(128) NOT NULL,
  started_at   TIMESTAMP    NOT NULL,
  finished_at  TIMESTAMP    NOT NULL,
  outcome      VARCHAR(16)  NOT NULL,                -- SUCCESS | FAILED
  error        VARCHAR(4000),
  PRIMARY KEY (item_id, attempt)
);
CREATE INDEX dbq_attempt_finished_ix ON dbq_attempt (queue_name, finished_at);   -- P7, P10, P11, P18

-- One row per queue per minute, written by the P18 job. Needed by: P3, P4, P11 (baseline), P15, P19, P20. Keeps history off the hot table.
CREATE TABLE dbq_snapshot (
  queue_name     VARCHAR(64) NOT NULL,
  taken_at       TIMESTAMP   NOT NULL,              -- truncated to the minute
  waiting        INT         NOT NULL,
  scheduled      INT         NOT NULL,
  in_flight      INT         NOT NULL,
  stuck          INT         NOT NULL,
  dead           INT         NOT NULL,
  oldest_wait_s  INT,                                -- NULL when nothing is waiting
  arrived_1m     INT         NOT NULL,
  completed_1m   INT         NOT NULL,
  failed_1m      INT         NOT NULL,
  PRIMARY KEY (queue_name, taken_at)
);

-- Every operator action, with maker and checker. Needed by: P16 (journey), P17 (all actions).
CREATE TABLE dbq_action_audit (
  id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  actor       VARCHAR(64)   NOT NULL,
  approver    VARCHAR(64),                           -- four-eyes: required for bulk actions
  action      VARCHAR(32)   NOT NULL,                -- RELEASE_STALE_CLAIMS | RETRY_DEAD | CANCEL | PAUSE | RESUME
  queue_name  VARCHAR(64)   NOT NULL,
  predicate   VARCHAR(1000) NOT NULL,                -- human-readable WHERE clause that was applied
  expected    INT,                                   -- dry-run count shown to the operator
  affected    INT           NOT NULL,
  item_ids    BIGINT[],                              -- Oracle: child table or JSON; SQL Server: JSON
  reason      VARCHAR(1000) NOT NULL,
  created_at  TIMESTAMP     NOT NULL
);

-- Error fingerprint: last_error with volatile parts (quoted values, uuids, numbers) masked so identical failures group.
-- Needed by: P9, P10, P11, P17 (retry dead by fingerprint). Alternative: workers write an error_code column when they fail.
CREATE OR REPLACE FUNCTION dbq_fingerprint(msg TEXT) RETURNS TEXT
  LANGUAGE sql IMMUTABLE PARALLEL SAFE AS $$
  SELECT left(regexp_replace(regexp_replace(regexp_replace(msg,
           '''[^'']*''', '''?''', 'g'),
           '[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}', '<uuid>', 'g'),
           '[0-9]+', '#', 'g'), 300)
$$;

-- ---------------------------------------------------------------------------
-- Test harness only: a frozen clock so every query in panels.sql is reproducible.
-- Production replaces dbq_now() with LOCALTIMESTAMP (store timestamps in UTC on every service).
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION dbq_now() RETURNS TIMESTAMP
  LANGUAGE sql STABLE AS $$ SELECT TIMESTAMP '2026-10-15 12:06:00' $$;
